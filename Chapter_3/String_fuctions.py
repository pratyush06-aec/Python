name= "harry"
print(len(name))             # Checks the string length.
print(name.endswith("y"))    # Checks whether the string ends with the letters mentined inside the ().
print(name.startswith("H"))   ## Checks whether the string starts with the letters mentined inside the ().
                              ## It's also case sensitive.
print(name.count("r"))       # Counts the number of times the letter mentioned inside the () appears in the string.
print(name.capitalize())      # Capitalizes the first letter of the string.